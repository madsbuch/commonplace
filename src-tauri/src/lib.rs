type SyncState<'a> = tauri::State<'a, std::sync::Arc<sync::service::SyncService>>;

/// Starts sync once the frontend has loaded (and so migrated) the database.
#[tauri::command]
async fn sync_start(app: tauri::AppHandle, svc: SyncState<'_>) -> Result<(), String> {
    let pool = db_pool(&app).await?;
    svc.start(app.clone(), pool).await?;
    // Spec: SYN-17
    // Android also syncs with the app closed, every half hour on Wi-Fi.
    use tauri_plugin_sync_background::SyncBackgroundExt;
    if let Ok(dir) = app.path().app_config_dir() {
        let db_path = dir.join(DB_FILE).to_string_lossy().into_owned();
        if let Err(e) = app
            .sync_background()
            .schedule(tauri_plugin_sync_background::ScheduleArgs { db_path })
        {
            eprintln!("sync: couldn't schedule background sync: {e}");
        }
    }
    Ok(())
}

// Spec: SYN-16
/// Before anything is written to a freshly opened database: a copy of it
/// from elsewhere (restored, put back) takes a new device id (instance.rs).
#[tauri::command]
async fn sync_check_instance(app: tauri::AppHandle) -> Result<(), String> {
    let pool = db_pool(&app).await?;
    let dir = app.path().app_config_dir().map_err(|e| e.to_string())?;
    if let sync::instance::Check::Rotated { old_id, new_id } =
        sync::instance::check(&pool, &dir.join(DB_FILE)).await?
    {
        eprintln!("sync: this database was a copy from elsewhere; device {old_id} is now {new_id}");
    }
    Ok(())
}

/// Marks an exported copy of the database as a copy (instance.rs).
#[tauri::command]
async fn mark_db_copy(path: String) -> Result<(), String> {
    sync::instance::mark_copy(std::path::Path::new(&path)).await
}

#[tauri::command]
async fn sync_status(svc: SyncState<'_>) -> Result<sync::service::Status, String> {
    sync::service::status(svc.pool()?, &svc).await
}

#[tauri::command]
async fn sync_set_name(svc: SyncState<'_>, name: String) -> Result<(), String> {
    sync::service::set_name(svc.pool()?, &name).await?;
    svc.kick();
    Ok(())
}

// Spec: SYN-9
/// A pairing code for the QR, good for one device for `sync.pairing-lifetime`.
#[tauri::command]
async fn sync_offer(svc: SyncState<'_>) -> Result<String, String> {
    svc.offer().await
}

#[tauri::command]
fn sync_cancel_offer(svc: SyncState<'_>) {
    svc.cancel_offer();
}

/// Joins a book. `replace`: this device holds data, and the author has
/// agreed to have it replaced (a copy is saved first).
#[tauri::command]
async fn sync_join(
    app: tauri::AppHandle,
    svc: SyncState<'_>,
    code: String,
    replace: bool,
) -> Result<sync::service::JoinResult, String> {
    svc.join(&app, &code, replace).await
}

#[tauri::command]
fn sync_now(svc: SyncState<'_>) {
    svc.kick();
}

#[tauri::command]
async fn sync_remove_device(svc: SyncState<'_>, id: String) -> Result<(), String> {
    sync::service::remove_device(svc.pool()?, &id).await?;
    svc.kick();
    Ok(())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_http::init())
        .plugin(
            tauri_plugin_sql::Builder::default()
                .add_migrations(DB_URL, migrations())
                .build(),
        )
        .plugin(tauri_plugin_sync_background::init())
        .manage(std::sync::Arc::new(sync::service::SyncService::default()));

    // Scanning the pairing QR code.
    #[cfg(mobile)]
    let builder = builder.plugin(tauri_plugin_barcode_scanner::init());

    builder
        .setup(|app| {
            // A development build never runs as the real app: it would open
            // the real database, and with sync, whatever unfinished code does
            // to it would reach every device. `bun run tauri dev` runs it as
            // "Commonplace Dev" (scripts/tauri.mjs); anything else is stopped here.
            // Spec: DEV-2
            #[cfg(all(debug_assertions, desktop))]
            if app.config().identifier == PRODUCTION_IDENTIFIER {
                eprintln!(
                    "\nThis is a development build running as the real Commonplace ({PRODUCTION_IDENTIFIER}),\n\
                     which would open your real database. Start it with `bun run tauri dev`,\n\
                     which runs it as \"Commonplace Dev\" with its own data.\n"
                );
                std::process::exit(1);
            }
            let _ = app;
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            sync_start,
            sync_check_instance,
            mark_db_copy,
            sync_status,
            sync_set_name,
            sync_offer,
            sync_cancel_offer,
            sync_join,
            sync_now,
            sync_remove_device,
            library_save_file,
            library_read_file,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
