/// The database, in app_config_dir (tauri-plugin-sql resolves it there).
const DB_URL: &str = "sqlite:book.db";
/// Its file name in app_config_dir, for what reads the file itself.
const DB_FILE: &str = "book.db";

/// The real app's identifier: its data folder is named after it. Development
/// builds run under another (see src-tauri/tauri.dev.conf.json).
#[allow(dead_code)]
const PRODUCTION_IDENTIFIER: &str = "com.madsbuch.mybook";

