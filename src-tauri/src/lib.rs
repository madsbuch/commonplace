#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_http::init())
        .plugin(
            tauri_plugin_sql::Builder::default()
                .add_migrations(DB_URL, migrations())
                .build(),
        )
        .plugin(tauri_plugin_sync_background::init())
        // Spec: AUD-10
        .plugin(tauri_plugin_audio_player::init())
        // Spec: WORK-2, WORK-3
        .plugin(tauri_plugin_background_work::init())
        // Spec: tandem.SYN-5
        .plugin(tauri_plugin_lan::init())
        // Spec: LIB-28
        .plugin(tauri_plugin_page_render::init())
        .manage(work::Work::default())
        .manage(std::sync::Arc::new(sync::service::SyncService::default()))
        .manage(std::sync::Arc::new(audio::render::AudioService::default()));

    // Scanning the pairing QR code.
    #[cfg(mobile)]
    let builder = builder.plugin(tauri_plugin_barcode_scanner::init());
    // Spec: LEAN-7
    #[cfg(desktop)]
    let builder = builder.manage(std::sync::Arc::new(lean::service::LeanService::default()));

    builder
        .setup(|app| {
            // A development build never runs as the real app: it would open
            // the real database, and with sync, whatever unfinished code does
            // to it would reach every device. `bun run tauri dev` runs it as
            // "Commonplace Dev" (scripts/tauri.mjs); anything else is stopped here.
            // Spec: DEV-2
            #[cfg(all(debug_assertions, desktop))]
            if app.config().identifier == PRODUCTION_IDENTIFIER {
                eprintln!(
                    "\nThis is a development build running as the real Commonplace ({PRODUCTION_IDENTIFIER}),\n\
                     which would open your real database. Start it with `bun run tauri dev`,\n\
                     which runs it as \"Commonplace Dev\" with its own data.\n"
                );
                std::process::exit(1);
            }
            // Spec: APP-13
            // A computer's folders under the app's earlier identifier move
            // over, before anything opens the database.
            #[cfg(desktop)]
            {
                let p = app.path();
                let dirs: Vec<std::path::PathBuf> = [p.app_config_dir(), p.app_data_dir(), p.app_local_data_dir()].into_iter().flatten().collect();
                for (old, new) in earlier::folders(&dirs, &app.config().identifier) {
                    match earlier::move_into(&old, &new) {
                        Ok(0) => {}
                        Ok(n) => diagnostics::report(
                            app.handle(),
                            diagnostics::Level::Info,
                            "app",
                            &format!("Moved {n} things from {} to {}, the app's new name.", old.display(), new.display()),
                        ),
                        Err(e) => diagnostics::report(
                            app.handle(),
                            diagnostics::Level::Error,
                            "app",
                            &format!("Couldn't move {} to {}: {e}", old.display(), new.display()),
                        ),
                    }
                }
            }
            // Spec: DIAG-2
            // A crash is written beside the database, to be taken in next time.
            if let Ok(dir) = app.path().app_config_dir() {
                diagnostics::install_panic_hook(dir);
            }
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            sync_start,
            sync_check_instance,
            mark_db_copy,
            sync_status,
            sync_set_name,
            sync_offer,
            sync_cancel_offer,
            sync_join,
            sync_now,
            sync_check,
            sync_announce,
            sync_peer_found,
            web_get,
            web_render,
            sync_remove_device,
            library_save_file,
            library_read_file,
            audio_listen,
            audio_make_all,
            audio_forget,
            audio_piece,
            audio_read,
            audio_native_play,
            lean_status,
            lean_set_up,
            lean_check,
            lean_goal,
            work_begin,
            work_end,
            work_running,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
